QString I18n::tr(const QString& pt) {
    if (g_lang == "pt") return pt;
    if (g_lang == "pt_PT") return toPtPT(pt);
    const QHash<QString, QString>& d = g_lang == "es" ? es() : en();
    const auto it = d.constFind(pt);
    if (it != d.constEnd()) return it.value();
    if (g_lang == "es") {
        const auto e = en().constFind(pt);
        if (e != en().constEnd()) return e.value();
    }
    return g_lang == "en" ? pt : pt;
}
